def sha(p, chunk=1 << 22):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for b in iter(lambda: f.read(chunk), b''):
            h.update(b)
    return h.hexdigest()


def rd(p):
    return open(p, encoding='utf-8', errors='replace').read().rstrip('\n')


